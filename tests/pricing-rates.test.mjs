import test from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import vm from "node:vm";
const read=p=>fs.readFileSync(new URL("../"+p,import.meta.url),"utf8");
test("retail FX is independent of Yassen supplier ILS rate and base markup is 13%",()=>{
 const migrations=read("supabase/migrations/20261016020000_separate_supplier_pricing.sql");
 const rates=read("supabase/migrations/20261016021000_margin_controls_middle_east_rates.sql");
 assert.match(migrations,/new_fx numeric:=3\.20/);
 assert.match(migrations,/margin_percent=13/);
 assert.match(migrations,/per_usd=3\.35 WHERE currency='ILS'/);
 assert.match(rates,/f90_manager_supplier_pricing/);
 const supplierCost=100/3.2,saleUSD=supplierCost*1.13,retailShekels=saleUSD*3.35;
 assert.ok(Math.abs(retailShekels-118.296875)<1e-8);
 assert.equal(supplierCost,31.25);
 assert.equal(saleUSD,35.3125);
});
test("price controls use protected RPCs and preserve supplier import prices",()=>{
 const ui=read("f90-pricing-admin.js");
 const backend=read("supabase/functions/f90-platform/index.ts");
 const sql=read("supabase/migrations/20261016021000_margin_controls_middle_east_rates.sql");
 assert.doesNotThrow(()=>new vm.Script(ui));
 assert.match(ui,/f90_manager_supplier_pricing/);
 assert.match(ui,/f90_manager_extra_margin/);
 assert.match(sql,/f90_private\.require_actor\(auth\.uid\(\),ARRAY\['manager'\]\)/);
 assert.match(sql,/REVOKE ALL ON FUNCTION public\.f90_manager_supplier_pricing/);
 assert.match(sql,/f90_private\.category_extra_margin/);
 assert.match(backend,/const supplierFee=p\.adapter==="yassen"/);
 assert.match(backend,/supplier_ils_per_usd/);
 assert.match(backend,/extraFor\(chosenCategoryId\)/);
 assert.doesNotMatch(ui,/service_role|api_key|secret/i);
});
